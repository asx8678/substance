//! The check registry: one [`CheckMeta`] per [`CheckId`], in ID order (M0-T03).

use crate::check::{
    Axis, CheckId, CheckStatus, Confidence, Family, GateRule, Level, Milestone, Need, Severity,
};

/// Everything the evaluator knows about one check before it runs.
#[derive(Debug, Clone, Copy, PartialEq, Eq)]
pub struct CheckMeta {
    /// The check ID.
    pub id: CheckId,
    /// The catalog title.
    pub title: &'static str,
    /// The check family, equal to the ID's prefix letter.
    pub family: Family,
    /// The destructiveness level, absent for reserved IDs and I03.
    pub level: Option<Level>,
    /// The default severity (ADR-0010).
    pub severity: Severity,
    /// The axes this check feeds (ADR-0011 assigns the ones the plan leaves out).
    pub axes: &'static [Axis],
    /// When a failure gates the run.
    pub gate: GateRule,
    /// What the check needs before it can run.
    pub needs: &'static [Need],
    /// The milestone that delivers the check.
    pub milestone: Milestone,
    /// How far the check has been built.
    pub status: CheckStatus,
    /// The confidence a finding starts with; the 3-of-3 rule may set `flaky`.
    pub default_confidence: Confidence,
}

impl CheckMeta {
    /// Whether this check is a hard gate, unconditionally or through a sub-check.
    #[must_use]
    pub fn is_gate(&self) -> bool {
        match self.gate {
            GateRule::None => false,
            GateRule::Always | GateRule::SubChecks(_) => true,
        }
    }
}

