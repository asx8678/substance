/// Looks a check up by ID. Total, because the registry covers every ID.
#[must_use]
pub const fn meta(id: CheckId) -> &'static CheckMeta {
    &REGISTRY[id as usize]
}

const fn assert_registry_shape() {
    assert!(
        REGISTRY.len() == CheckId::COUNT,
        "registry length must equal CheckId::COUNT"
    );
    let mut index = 0;
    while index < REGISTRY.len() {
        assert!(
            REGISTRY[index].id as usize == index,
            "registry must be in CheckId order"
        );
        index += 1;
    }
}

const _: () = assert_registry_shape();
